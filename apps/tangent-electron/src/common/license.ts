/**
 * Licence keys: the format, and everything about them that needs no crypto.
 *
 * Shared by the main process (which verifies signatures) and the renderer (which shows
 * status and collects a key), so it must not import from `electron` or `node:crypto`.
 * Verification itself lives in main/license.ts.
 *
 * ## Format
 *
 *     OSINT-<base64url(payload JSON)>.<base64url(Ed25519 signature)>
 *
 * The signature covers the base64url payload string exactly as it appears in the key, not
 * the decoded JSON — so re-serialising the payload can never change what was signed, and
 * a key survives any future change to how we format JSON.
 *
 * Offline by design: a key carries who it was issued to and when it expires, and is
 * checked against a public key compiled into the app. No activation server, so the app
 * works on an air-gapped machine — the trade-off being that a leaked key cannot be
 * revoked without shipping a build.
 */

/** Prefix, so a key is recognisable when pasted somewhere it does not belong. */
export const LICENSE_PREFIX = 'OSINT-'

/**
 * The Ed25519 public key that valid licence keys are signed against, base64, raw 32 bytes.
 *
 * Public by nature — embedding it gives nothing away. Its private counterpart is the one
 * that matters; it is generated by `scripts/license-keygen.mjs`, never committed, and
 * `.gitignore` carries a rule for it.
 *
 * Replacing this value invalidates every key already issued.
 */
export const LICENSE_PUBLIC_KEY_B64 = 'vfJVwoKdSteUyfyNsxKyz9iDzTBV7PN0fUL7iakm3sE='

export interface LicensePayload {
	/** Format version, so a future change can be told apart from a corrupt key. */
	v: number
	/** Who the licence is issued to. Shown in settings. */
	name: string
	email?: string
	/** ISO date (YYYY-MM-DD) the key was issued. */
	issued?: string
	/** ISO date the key stops working, or null/absent for a perpetual licence. */
	expires?: string | null
	/** Informational; nothing enforces it offline. */
	seats?: number
}

export type LicenseFailure =
	| 'missing'
	| 'malformed'
	| 'bad-signature'
	| 'expired'
	| 'unsupported-version'

export interface LicenseStatus {
	valid: boolean
	/** Present when valid. */
	payload?: LicensePayload
	/** Present when not valid. */
	reason?: LicenseFailure
	/** Sentence to put in front of the user. Always set when `valid` is false. */
	message?: string
}

/** The highest payload version this build understands. */
export const LICENSE_FORMAT_VERSION = 1

export function base64UrlDecode(value: string): Uint8Array {
	const padded = value.replace(/-/g, '+').replace(/_/g, '/')
	const binary = atob(padded + '='.repeat((4 - (padded.length % 4)) % 4))
	const bytes = new Uint8Array(binary.length)
	for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
	return bytes
}

export function base64UrlEncode(bytes: Uint8Array): string {
	let binary = ''
	for (const byte of bytes) binary += String.fromCharCode(byte)
	return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

/**
 * Whitespace-tolerant: a key arrives pasted out of an email or a PDF, where it may have
 * been wrapped across lines. Everything else about it is case- and character-exact.
 */
export function normalizeLicenseKey(key: string): string {
	return (key ?? '').replace(/\s+/g, '')
}

export interface ParsedLicenseKey {
	/** The signed message: the base64url payload, exactly as it appeared in the key. */
	signedText: string
	signature: Uint8Array
	payload: LicensePayload
}

/**
 * Splits a key into its parts and decodes the payload. Says nothing about whether the
 * signature is good — that needs crypto, and lives in main/license.ts.
 */
export function parseLicenseKey(key: string): ParsedLicenseKey | null {
	const normalized = normalizeLicenseKey(key)
	if (!normalized.startsWith(LICENSE_PREFIX)) return null

	const body = normalized.slice(LICENSE_PREFIX.length)
	const dot = body.indexOf('.')
	if (dot <= 0 || dot === body.length - 1) return null

	const signedText = body.slice(0, dot)
	const signatureText = body.slice(dot + 1)
	// A second separator means the key was mangled, not that we should take the first cut.
	if (signatureText.includes('.')) return null

	try {
		const payload = JSON.parse(new TextDecoder().decode(base64UrlDecode(signedText)))
		if (!payload || typeof payload !== 'object' || typeof payload.v !== 'number') return null
		return { signedText, signature: base64UrlDecode(signatureText), payload }
	}
	catch {
		return null
	}
}

/** True once the day named by `expires` is over. A key is good through its expiry date. */
export function isExpired(payload: LicensePayload, now = new Date()): boolean {
	if (!payload.expires) return false
	const expiry = new Date(`${payload.expires}T23:59:59.999Z`)
	if (Number.isNaN(expiry.getTime())) return true
	return now.getTime() > expiry.getTime()
}

/** The sentence shown to the user for each way a key can fail. */
export function licenseFailureMessage(reason: LicenseFailure): string {
	switch (reason) {
		case 'missing':
			return 'Enter your licence key to use OSINT Copilot.'
		case 'malformed':
			return 'That does not look like an OSINT Copilot licence key. Check that you copied all of it.'
		case 'bad-signature':
			return 'That licence key is not valid. Check for a typo, or ask for a replacement.'
		case 'expired':
			return 'That licence key has expired. Renew it to keep using OSINT Copilot.'
		case 'unsupported-version':
			return 'That licence key needs a newer version of OSINT Copilot.'
	}
}
