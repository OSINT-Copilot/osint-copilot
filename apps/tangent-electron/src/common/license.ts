/**
 * Licence keys: the format, and everything about them that needs no crypto.
 *
 * Shared by the main process (which verifies signatures) and the renderer (which shows
 * status and collects a key), so it must not import from `electron` or `node:crypto`.
 * Verification itself lives in main/license.ts.
 *
 * ## Format
 *
 *     OSINT-<base64url(payload JSON)>.<base64url(Ed25519 signature)>
 *
 * The signature covers the base64url payload string exactly as it appears in the key, not
 * the decoded JSON — so re-serialising the payload can never change what was signed, and
 * a key survives any future change to how we format JSON.
 *
 * Offline by design: a key carries who it was issued to and when it expires, and is
 * checked against a public key compiled into the app. No activation server, so the app
 * works on an air-gapped machine — the trade-off being that a leaked key cannot be
 * revoked without shipping a build.
 *
 * ## The other kind of key
 *
 * Most users do not have one of those. They have a *subscription key*: the API key their
 * account issues on the OSINT Copilot dashboard (the `ready-saas` web app), which the
 * desktop app checks over HTTPS and which carries a tier — trial, basic or premium.
 *
 * The two are told apart by shape, not by asking the user: an offline key starts with
 * `OSINT-`, a subscription key is a plain URL-safe token. See `licenseKeyKind`. Both end
 * up as the same `LicenseStatus`, so everything downstream of the gate treats them alike.
 *
 * | | offline key | subscription key |
 * |---|---|---|
 * | checked by | a signature, on this machine | the dashboard, over HTTPS |
 * | needs network | never | on activation, and periodically after |
 * | can be revoked | no | yes |
 * | tier | whatever it was signed with (default premium) | whatever the plan says today |
 */

/** Prefix, so a key is recognisable when pasted somewhere it does not belong. */
export const LICENSE_PREFIX = 'OSINT-'

/**
 * The Ed25519 public key that valid licence keys are signed against, base64, raw 32 bytes.
 *
 * Public by nature — embedding it gives nothing away. Its private counterpart is the one
 * that matters; it is generated by `scripts/license-keygen.mjs`, never committed, and
 * `.gitignore` carries a rule for it.
 *
 * Replacing this value invalidates every key already issued.
 */
export const LICENSE_PUBLIC_KEY_B64 = 'vfJVwoKdSteUyfyNsxKyz9iDzTBV7PN0fUL7iakm3sE='

/* ------------------------------------------------------------------ *
 * Tiers and entitlements
 * ------------------------------------------------------------------ */

/**
 * What the app sells. Three, deliberately — the dashboard has more plans than this and
 * will grow more, and mapping them down happens on the server (orders/entitlements.py) so
 * a new plan never requires a new desktop build.
 */
export type AppTier = 'trial' | 'basic' | 'premium'

export const APP_TIERS: readonly AppTier[] = ['trial', 'basic', 'premium'] as const

/** Ordering, for "premium or better" style checks. */
const TIER_RANK: Record<AppTier, number> = { trial: 0, basic: 1, premium: 2 }

export function isAppTier(value: unknown): value is AppTier {
	return typeof value === 'string' && (APP_TIERS as readonly string[]).includes(value)
}

export function tierAtLeast(tier: AppTier | undefined, minimum: AppTier): boolean {
	if (!tier) return false
	return TIER_RANK[tier] >= TIER_RANK[minimum]
}

export function tierDisplayName(tier: AppTier): string {
	switch (tier) {
		case 'trial': return 'Trial'
		case 'basic': return 'Basic'
		case 'premium': return 'Premium'
	}
}

/**
 * The individual capabilities a licence grants.
 *
 * Named for what the app does, not for what the server's columns are called — the server
 * speaks `allow_chat_view`, and the translation happens once, where the response is
 * parsed. Every field is required, so adding one is a compile error at each place that
 * builds an entitlement set rather than a silently-undefined check at each place that
 * reads one.
 */
export interface Entitlements {
	/** The OSINT layer at all: entity extraction, the graph, the canvas. */
	osint: boolean
	/** The chat view / local agent conversation surface. */
	chat: boolean
	/** AI-driven entity and relationship extraction into the graph. */
	graphAutomation: boolean
	/** Pointing the app at your own LLM endpoint instead of the bundled one. */
	customModels: boolean
	/** Running an agent locally rather than through the dashboard. */
	localAgent: boolean
}

/** Everything on. What an offline `premium` key grants, and the shape of a full licence. */
export const FULL_ENTITLEMENTS: Entitlements = {
	osint: true,
	chat: true,
	graphAutomation: true,
	customModels: true,
	localAgent: true,
}

/** Everything off. The safe answer when there is no licence to read. */
export const NO_ENTITLEMENTS: Entitlements = {
	osint: false,
	chat: false,
	graphAutomation: false,
	customModels: false,
	localAgent: false,
}

/**
 * What each tier grants when nothing more specific is known.
 *
 * Only a fallback. A subscription key carries per-feature flags set on the plan itself,
 * and those win — an admin can enable one feature for one plan without touching the app.
 * This table is what an *offline* key gets, and what a subscription answer falls back to
 * if the server ever omits its flags.
 */
export function entitlementsForTier(tier: AppTier): Entitlements {
	switch (tier) {
		case 'trial':
			return { osint: true, chat: true, graphAutomation: false, customModels: false, localAgent: false }
		case 'basic':
			return { osint: true, chat: true, graphAutomation: true, customModels: false, localAgent: false }
		case 'premium':
			return { ...FULL_ENTITLEMENTS }
	}
}

/* ------------------------------------------------------------------ *
 * Subscription keys
 * ------------------------------------------------------------------ */

export type LicenseKeyKind = 'offline' | 'subscription'

/**
 * The dashboard this build checks subscription keys against.
 *
 * Overridable at run time only outside a packaged build (see main/license-subscription.ts),
 * so a shipped application cannot be pointed at a friendlier server by setting a variable.
 */
export const DEFAULT_LICENSE_SERVER = 'https://osint-copilot.com'

/** Path on that server. Answers with `{ ok, license }`; see orders/report_views.py. */
export const LICENSE_ENDPOINT = '/api/desktop/license'

/**
 * How long the app keeps working on a cached answer with no contact with the server.
 *
 * The trade-off, stated plainly: too short and a analyst on a plane loses their tools;
 * too long and a cancelled subscription keeps working. Two weeks is chosen for the first
 * of those, because this is field software and connectivity is not a given.
 */
export const OFFLINE_GRACE_DAYS = 14

/** How old a cached answer may be before the app tries the server again. */
export const REVALIDATE_AFTER_HOURS = 20

/** What the dashboard told us about a subscription key, as the app stores and shows it. */
export interface SubscriptionDetails {
	tier: AppTier
	/** Internal plan name, e.g. `ADVANCED`. */
	plan: string
	/** What to show the user, e.g. `Advanced`. */
	planDisplayName: string
	email?: string
	name?: string
	isTrial: boolean
	/** The dashboard's own status string, e.g. `trialing`. Shown, never branched on. */
	subscriptionStatus?: string
	/**
	 * The instant access stops, or null for none. Used for the expiry *check*.
	 *
	 * Not for display: it is the end of the last day, so rendering it in a timezone
	 * ahead of the server's shows the day after the one the user is billed to.
	 */
	expires?: string | null
	/** The plain `YYYY-MM-DD` the subscription runs to. What to show the user. */
	endDate?: string | null
	/** Remaining report credits at the last check. Informational; the server enforces it. */
	credits: number
	features: Entitlements
	/** ISO timestamp of the last answer from the server. Drives the grace period. */
	checkedAt: string
}

/**
 * Which kind of key this is — by shape alone, so the user never has to say.
 *
 * A subscription key is `secrets.token_urlsafe(40)[:40]` on the server: URL-safe base64
 * with no prefix. The length range is generous rather than exactly 40 so that changing
 * the server's key length does not lock existing users out of a build already shipped.
 */
export function licenseKeyKind(key: string): LicenseKeyKind | null {
	const normalized = normalizeLicenseKey(key)
	if (!normalized) return null
	if (normalized.startsWith(LICENSE_PREFIX)) return 'offline'
	if (/^[A-Za-z0-9_-]{16,200}$/.test(normalized)) return 'subscription'
	return null
}

/** True once a cached answer is old enough to be worth re-checking. */
export function shouldRevalidate(checkedAt: string, now = new Date()): boolean {
	const age = now.getTime() - new Date(checkedAt).getTime()
	if (Number.isNaN(age)) return true
	return age >= REVALIDATE_AFTER_HOURS * 60 * 60 * 1000
}

/** True once a cached answer is too old to keep honouring without contact. */
export function graceExhausted(checkedAt: string, now = new Date()): boolean {
	const age = now.getTime() - new Date(checkedAt).getTime()
	// An unparseable timestamp is treated as exhausted: the alternative is trusting a
	// value we cannot read, which is exactly what an edited cache file would look like.
	if (Number.isNaN(age)) return true
	return age > OFFLINE_GRACE_DAYS * 24 * 60 * 60 * 1000
}

/** Days of grace left on a cached answer, floored at zero. For the "working offline" note. */
export function graceDaysRemaining(checkedAt: string, now = new Date()): number {
	const age = now.getTime() - new Date(checkedAt).getTime()
	if (Number.isNaN(age)) return 0
	const remaining = OFFLINE_GRACE_DAYS - age / (24 * 60 * 60 * 1000)
	return Math.max(0, Math.floor(remaining))
}

export interface LicensePayload {
	/** Format version, so a future change can be told apart from a corrupt key. */
	v: number
	/** Who the licence is issued to. Shown in settings. */
	name: string
	email?: string
	/** ISO date (YYYY-MM-DD) the key was issued. */
	issued?: string
	/** ISO date the key stops working, or null/absent for a perpetual licence. */
	expires?: string | null
	/** Informational; nothing enforces it offline. */
	seats?: number
	/**
	 * Which tier this key grants. Absent means `premium`: keys minted before tiers
	 * existed were sold as the full product, and must keep behaving that way.
	 */
	tier?: AppTier
}

export type LicenseFailure =
	| 'missing'
	| 'malformed'
	| 'bad-signature'
	| 'expired'
	| 'unsupported-version'
	// Subscription keys only, from here down.
	/** The dashboard has never heard of this key. */
	| 'unknown-key'
	/** The key existed and was switched off. */
	| 'revoked'
	/** The key is fine; the subscription behind it has lapsed or been cancelled. */
	| 'subscription-inactive'
	/** Unreachable dashboard, and the last good answer is now too old to keep trusting. */
	| 'offline-too-long'
	/** The dashboard answered, but not with anything this build can read. */
	| 'server-error'

export interface LicenseStatus {
	valid: boolean
	/** Which kind of key produced this. Absent only before the first check. */
	source?: LicenseKeyKind
	/** Present when an offline key produced this. */
	payload?: LicensePayload
	/** Present when a subscription key produced this, valid or not. */
	subscription?: SubscriptionDetails
	/**
	 * What the app may do. Always present when `valid`, whichever kind of key it came
	 * from, so feature checks never have to know which one it was.
	 */
	tier?: AppTier
	entitlements?: Entitlements
	/**
	 * True when this answer came from the cache because the dashboard could not be
	 * reached. Access continues; the UI says so rather than pretending it is fresh.
	 */
	stale?: boolean
	/** Present when not valid. */
	reason?: LicenseFailure
	/** Sentence to put in front of the user. Always set when `valid` is false. */
	message?: string
}

/** The highest payload version this build understands. */
export const LICENSE_FORMAT_VERSION = 1

export function base64UrlDecode(value: string): Uint8Array {
	const padded = value.replace(/-/g, '+').replace(/_/g, '/')
	const binary = atob(padded + '='.repeat((4 - (padded.length % 4)) % 4))
	const bytes = new Uint8Array(binary.length)
	for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
	return bytes
}

export function base64UrlEncode(bytes: Uint8Array): string {
	let binary = ''
	for (const byte of bytes) binary += String.fromCharCode(byte)
	return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

/**
 * Whitespace-tolerant: a key arrives pasted out of an email or a PDF, where it may have
 * been wrapped across lines. Everything else about it is case- and character-exact.
 */
export function normalizeLicenseKey(key: string): string {
	return (key ?? '').replace(/\s+/g, '')
}

export interface ParsedLicenseKey {
	/** The signed message: the base64url payload, exactly as it appeared in the key. */
	signedText: string
	signature: Uint8Array
	payload: LicensePayload
}

/**
 * Splits a key into its parts and decodes the payload. Says nothing about whether the
 * signature is good — that needs crypto, and lives in main/license.ts.
 */
export function parseLicenseKey(key: string): ParsedLicenseKey | null {
	const normalized = normalizeLicenseKey(key)
	if (!normalized.startsWith(LICENSE_PREFIX)) return null

	const body = normalized.slice(LICENSE_PREFIX.length)
	const dot = body.indexOf('.')
	if (dot <= 0 || dot === body.length - 1) return null

	const signedText = body.slice(0, dot)
	const signatureText = body.slice(dot + 1)
	// A second separator means the key was mangled, not that we should take the first cut.
	if (signatureText.includes('.')) return null

	try {
		const payload = JSON.parse(new TextDecoder().decode(base64UrlDecode(signedText)))
		if (!payload || typeof payload !== 'object' || typeof payload.v !== 'number') return null
		return { signedText, signature: base64UrlDecode(signatureText), payload }
	}
	catch {
		return null
	}
}

/** True once the day named by `expires` is over. A key is good through its expiry date. */
export function isExpired(payload: LicensePayload, now = new Date()): boolean {
	if (!payload.expires) return false
	const expiry = new Date(`${payload.expires}T23:59:59.999Z`)
	if (Number.isNaN(expiry.getTime())) return true
	return now.getTime() > expiry.getTime()
}

/** The sentence shown to the user for each way a key can fail. */
export function licenseFailureMessage(reason: LicenseFailure): string {
	switch (reason) {
		case 'missing':
			return 'Enter your licence key to use OSINT Copilot.'
		case 'malformed':
			return 'That does not look like an OSINT Copilot licence key. Check that you copied all of it.'
		case 'bad-signature':
			return 'That licence key is not valid. Check for a typo, or ask for a replacement.'
		case 'expired':
			return 'That licence key has expired. Renew it to keep using OSINT Copilot.'
		case 'unsupported-version':
			return 'That licence key needs a newer version of OSINT Copilot.'
		case 'unknown-key':
			return 'That key is not recognised. Copy it again from your dashboard at ' +
				'osint-copilot.com, or check that you are signed in to the right account.'
		case 'revoked':
			return 'That key has been switched off. Generate a new one from your dashboard.'
		case 'subscription-inactive':
			return 'Your subscription is not active. Renew it on your dashboard to carry on.'
		case 'offline-too-long':
			return `OSINT Copilot has not been able to reach the licence server for ` +
				`${OFFLINE_GRACE_DAYS} days. Connect to the internet once to carry on working.`
		case 'server-error':
			return 'The licence server could not be reached. Check your connection and try again.'
	}
}
